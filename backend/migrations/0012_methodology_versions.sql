CREATE TABLE methodology_versions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  methodology_id BIGINT UNSIGNED NOT NULL,
  version_label VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title VARCHAR(200) NOT NULL DEFAULT '',
  free_summary TEXT NOT NULL,
  public_description TEXT NOT NULL,
  changelog TEXT NOT NULL,
  editorial_status ENUM('DRAFT', 'PUBLISHED', 'SUPERSEDED') NOT NULL DEFAULT 'DRAFT',
  access_state ENUM('ALLOWED', 'SUSPENDED') NOT NULL DEFAULT 'ALLOWED',
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NOT NULL,
  reviewed_by BIGINT UNSIGNED NULL,
  reviewed_at DATETIME(6) NULL,
  reviewed_revision INT UNSIGNED NULL,
  review_note TEXT NULL,
  published_at DATETIME(6) NULL,
  deleted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL,
  UNIQUE KEY version_label_unique (methodology_id, version_label),
  UNIQUE KEY version_ownership (methodology_id, id),
  KEY version_listing (methodology_id, deleted_at, id),
  FOREIGN KEY (methodology_id) REFERENCES methodologies(id) ON DELETE RESTRICT,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT,
  FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE RESTRICT,
  CHECK (editorial_status = 'DRAFT' OR (published_at IS NOT NULL AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_revision IS NOT NULL AND review_note IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
